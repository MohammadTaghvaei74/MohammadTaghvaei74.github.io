const assert=require('node:assert/strict');
const {candles,samples}=require('./history.js');
const p=(time,m=1,day='2026-10-28')=>({minute:`${day}T${time}:00+03:30`,market:m});
const full=Array.from({length:211},(_,i)=>p(`${String(Math.floor((540+i)/60)).padStart(2,'0')}:${String((540+i)%60).padStart(2,'0')}`,i));
assert.equal(candles(full,'daily').length,1);
assert.deepEqual([candles(full,'daily')[0].o,candles(full,'daily')[0].h,candles(full,'daily')[0].l,candles(full,'daily')[0].c],[0,210,0,210]);
const gap=full.slice(); gap.splice(10,1); assert.equal(candles(gap,'daily').length,0);
assert.equal(candles(full,'1').length,211);
assert.equal(candles(full,'5').length,43);
assert.equal(candles(full,'30').length,8);
assert.equal(candles([p('09:15',null)],'1').length,0);
assert.equal(samples([p('09:15',1),p('09:16',2)]).length,2);
console.log('PASS: total-market only; exact 1m/5m/30m; complete daily; gaps and nulls excluded');

const assert=require('node:assert/strict');
const F=require('../market/observation-safety.js');
assert.equal(typeof F.freshness,'function','shared section freshness policy must exist');
const at=s=>Date.parse(s+'+03:30');
const check=(stamp,now,expected,opts={})=>assert.equal(F.freshness(F.range([{timestamp:stamp}]),{now:at(now),...opts}).status,expected,stamp+' @ '+now);
check('2026-11-01T10:00:00+03:30','2026-11-01T10:01:00','fresh');
check('2026-11-01T10:00:00+03:30','2026-11-01T10:01:00.001','stale');
check('2026-11-01T12:29:59+03:30','2026-11-01T12:30:00','fresh');
check('2026-11-01T12:29:00+03:30','2026-11-01T18:00:00','fresh');
check('2026-11-01T12:30:00+03:30','2026-11-01T18:00:00','fresh');
check('2026-10-28T12:30:00+03:30','2026-10-30T18:00:00','fresh');
check('2026-10-28T12:30:00+03:30','2026-10-31T08:59:59','fresh');
check('2026-10-28T12:30:00+03:30','2026-10-31T09:00:00','stale');
check('2026-11-01T12:30:00+03:30','2026-11-01T18:00:00','archive',{archive:true});
assert.equal(F.freshness(F.range([]),{now:at('2026-11-01T18:00:00')}).status,'unknown');
assert.equal(F.freshness(F.range([{generated_at:'2026-11-01T12:30:00+03:30'}]),{now:at('2026-11-01T18:00:00')}).status,'unknown');
check('2026-03-18T12:30:00+03:30','2026-03-24T18:00:00','fresh');
check('2026-11-01T12:30:00+03:30','2026-11-01T14:00:00','stale',{close:'15:00'});
check('2026-11-01T15:00:00+03:30','2026-11-01T18:00:00','fresh',{close:'15:00'});
check('2026-11-02T12:30:00+03:30','2026-11-01T18:00:00','unknown');
const daily=[{trading_date:'2026-11-01',complete:true,final_turnover_toman:3,source:'persisted 12:30 MarketWatch final snapshot; 2026-11-01T12:30:02+03:30'},{trading_date:'2026-10-31',complete:true,final_turnover_toman:2,source:'persisted 12:30 MarketWatch final snapshot; 2026-10-31T12:30:01+03:30'}];
assert.equal(typeof F.dailyRange,'function','turnover requires actual final source provenance');
assert.equal(F.dailyRange(daily).last,'2026-11-01T12:30:02+03:30');
assert.equal(F.dailyRange([{...daily[0],complete:false}]).unknown,true);
assert.equal(F.dailyRange([{...daily[0],source:'generated_at: 2026-11-01T12:30:02+03:30'}]).unknown,true);
assert.equal(F.dailyRange([{...daily[0],source:'persisted 12:30 MarketWatch final snapshot; 2026-11-01T12:29:02+03:30'}]).unknown,true);
assert.equal(F.freshness(F.dailyRange(daily),{now:at('2026-11-01T18:00:00'),daily:true,series:true}).status,'fresh');
assert.equal(F.freshness(F.range([{timestamp:'2026-11-01T12:30:00+03:30'},{timestamp:'2026-11-02T12:30:00+03:30'}]),{now:at('2026-11-01T18:00:00')}).status,'unknown');
console.log('freshness boundaries and provenance: passed');
